alter table public.insights
  add column if not exists insight_key text;

do $$
declare
  status_constraint record;
begin
  for status_constraint in
    select conname
    from pg_constraint
    where conrelid = 'public.insights'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%status%'
  loop
    execute format('alter table public.insights drop constraint %I', status_constraint.conname);
  end loop;
end;
$$;

update public.insights
set status = case lower(coalesce(status, ''))
  when 'closed' then 'actioned'
  when 'resolved' then 'actioned'
  when 'completed' then 'actioned'
  when 'dismissed' then 'dismissed'
  when 'actioned' then 'actioned'
  else 'open'
end
where status is null or lower(status) not in ('open', 'actioned', 'dismissed');

alter table public.insights
  alter column status set default 'open',
  alter column status set not null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.insights'::regclass
      and conname = 'insights_status_valid_check'
  ) then
    alter table public.insights
      add constraint insights_status_valid_check
      check (status in ('open', 'actioned', 'dismissed'));
  end if;
end;
$$;

create unique index if not exists insights_institution_key_idx
  on public.insights (institution_id, insight_key)
  where insight_key is not null;

create or replace function public.guard_insight_status_update()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if row(
    new.institution_id,
    new.type,
    new.severity,
    new.message,
    new.related_record_json,
    new.insight_key
  ) is distinct from row(
    old.institution_id,
    old.type,
    old.severity,
    old.message,
    old.related_record_json,
    old.insight_key
  ) then
    raise exception 'Insight details are generated by the system and cannot be edited';
  end if;

  if old.status <> 'open' or new.status not in ('actioned', 'dismissed') then
    raise exception 'Open insights can only be actioned or dismissed';
  end if;

  return new;
end;
$$;

create trigger insights_guard_updates
before update on public.insights
for each row execute function public.guard_insight_status_update();

create or replace function public.generate_institution_insights(p_institution_id uuid)
returns integer
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_inserted integer := 0;
  v_count integer := 0;
begin
  if auth.uid() is null then
    if coalesce(auth.role(), '') <> 'service_role' then
      raise exception 'Authentication required';
    end if;
  elsif not public.has_institution_role(
    p_institution_id,
    array['owner', 'principal', 'staff', 'authority']
  ) then
    raise exception 'Institution access denied';
  end if;

  with attendance_rows as (
    select
      a.student_id,
      a.class_id,
      a.term_id,
      a.attendance_date,
      a.status,
      row_number() over (
        partition by a.student_id, a.term_id
        order by a.attendance_date
      ) - row_number() over (
        partition by a.student_id, a.term_id, a.status
        order by a.attendance_date
      ) as streak_group
    from public.student_attendance a
    where a.institution_id = p_institution_id
  ),
  streaks as (
    select
      student_id,
      term_id,
      (array_agg(class_id order by attendance_date desc))[1] as class_id,
      min(attendance_date) as first_absence,
      max(attendance_date) as last_absence,
      count(*)::integer as consecutive_days
    from attendance_rows
    where status = 'absent'
    group by student_id, term_id, streak_group
    having count(*) >= 3
  )
  insert into public.insights (
    institution_id,
    type,
    severity,
    message,
    related_record_json,
    status,
    insight_key,
    created_at
  )
  select
    p_institution_id,
    'consecutive_absence',
    'high',
    format('Student %s has %s consecutive recorded absences.', s.student_id, s.consecutive_days),
    jsonb_build_object(
      'student_id', s.student_id,
      'class_id', s.class_id,
      'term_id', s.term_id,
      'first_absence', s.first_absence,
      'last_absence', s.last_absence,
      'consecutive_days', s.consecutive_days
    ),
    'open',
    format('absence:%s:%s', s.student_id, s.first_absence),
    now()
  from streaks s
  on conflict (institution_id, insight_key)
    where insight_key is not null
  do nothing;
  get diagnostics v_count = row_count;
  v_inserted := v_inserted + v_count;

  insert into public.insights (
    institution_id,
    type,
    severity,
    message,
    related_record_json,
    status,
    insight_key,
    created_at
  )
  select
    e.institution_id,
    'missing_result',
    'medium',
    format('A result is missing for student %s in %s.', e.student_id, a.subject),
    jsonb_build_object(
      'student_id', e.student_id,
      'class_id', e.class_id,
      'term_id', e.term_id,
      'subject', a.subject
    ),
    'open',
    format('result:%s:%s:%s:%s', e.student_id, e.class_id, e.term_id, lower(a.subject)),
    now()
  from public.student_enrollments e
  join public.assessments a
    on a.institution_id = e.institution_id
   and a.class_id = e.class_id
   and a.term_id = e.term_id
  where e.institution_id = p_institution_id
    and e.ended_at is null
    and not exists (
      select 1
      from public.results r
      where r.institution_id = e.institution_id
        and r.student_id = e.student_id
        and r.class_id = e.class_id
        and r.term_id = e.term_id
        and lower(r.subject) = lower(a.subject)
    )
  group by e.institution_id, e.student_id, e.class_id, e.term_id, a.subject
  on conflict (institution_id, insight_key)
    where insight_key is not null
  do nothing;
  get diagnostics v_count = row_count;
  v_inserted := v_inserted + v_count;

  return v_inserted;
end;
$$;

revoke all on function public.generate_institution_insights(uuid) from public, anon;
grant execute on function public.generate_institution_insights(uuid) to authenticated, service_role;
